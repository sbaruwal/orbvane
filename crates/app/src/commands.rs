/// A keyboard shortcut. `key` is a lowercase character or a named key like "\\".
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Shortcut {
    pub cmd: bool,
    pub shift: bool,
    pub alt: bool,
    pub ctrl: bool,
    pub key: &'static str,
}

const fn cmd(key: &'static str) -> Shortcut {
    Shortcut { cmd: true, shift: false, alt: false, ctrl: false, key }
}

const fn cmd_shift(key: &'static str) -> Shortcut {
    Shortcut { cmd: true, shift: true, alt: false, ctrl: false, key }
}

const fn plain(key: &'static str) -> Shortcut {
    Shortcut { cmd: false, shift: false, alt: false, ctrl: false, key }
}

const fn ctrl(key: &'static str) -> Shortcut {
    Shortcut { cmd: false, shift: false, alt: false, ctrl: true, key }
}

const fn ctrl_shift(key: &'static str) -> Shortcut {
    Shortcut { cmd: false, shift: true, alt: false, ctrl: true, key }
}

impl Shortcut {
    /// Whether a key press matches this shortcut.
    pub fn matches(&self, key: &str, cmd: bool, shift: bool, alt: bool, ctrl: bool) -> bool {
        self.key == key && self.cmd == cmd && self.shift == shift && self.alt == alt && self.ctrl == ctrl
    }

    /// The key as shown on a keycap.
    fn key_label(&self) -> String {
        match self.key {
            "space" => "Space".into(),
            "up" => "↑".into(),
            "down" => "↓".into(),
            "left" => "←".into(),
            "right" => "→".into(),
            k => k.to_uppercase(),
        }
    }

    /// The label split into keycaps: each modifier symbol, then the key.
    pub fn keycaps(&self) -> Vec<String> {
        let mut caps: Vec<String> = Vec::new();
        for (on, sym) in [(self.ctrl, "⌃"), (self.alt, "⌥"), (self.shift, "⇧"), (self.cmd, "⌘")] {
            if on {
                caps.push(sym.into());
            }
        }
        caps.push(self.key_label());
        caps
    }

    /// Accelerator string for the native menu.
    pub fn accelerator(&self) -> String {
        let mut parts = Vec::new();
        if self.ctrl {
            parts.push("Ctrl");
        }
        if self.alt {
            parts.push("Alt");
        }
        if self.shift {
            parts.push("Shift");
        }
        if self.cmd {
            parts.push("Cmd");
        }
        // muda's names ("UP", "SPACE", "I").
        let key = self.key.to_uppercase();
        parts.push(&key);
        parts.join("+")
    }
}

