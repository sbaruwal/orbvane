    /// Whether the command needs a git repository (hidden from the palette without one).
    pub fn needs_repo(self) -> bool {
        self.id().starts_with("git.") && !matches!(self, Command::GitInit | Command::GitClone)
    }

    pub fn from_id(id: &str) -> Option<Command> {
        Command::ALL.iter().copied().find(|c| c.id() == id).or_else(|| ext_command_named(id))
    }

    /// The built-in commands and the enabled extensions' palette commands.
    pub fn all() -> Vec<Command> {
        let mut all = Command::ALL.to_vec();
        EXT_COMMANDS.with(|e| all.extend(e.borrow().iter().enumerate().filter(|(_, c)| c.enabled && c.in_palette).map(|(i, _)| Command::Ext(i as u16))));
        all
    }

